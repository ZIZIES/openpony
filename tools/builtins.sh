#!/usr/bin/env bash
# usage: builtins.sh vars|table [dir]
#   vars  -> make variables listing every program (BFILES, BDIRS)
#   table -> C source for the shell's command table
#
# builtins/NAME.c        -> command NAME
# builtins/NAME/main.c   -> command NAME (the folder can hold more .c/.h files)
set -e
mode=$1
dir=${2:-builtins}
reserved=" help "

die() { echo "builtins: error: $*" >&2; exit 1; }

declare -A where mainsrc
files=()
dirs=()
names=()

register() {            # $1 = name, $2 = path shown in errors, $3 = file holding main()
    if [[ ! $1 =~ ^[a-z][a-z0-9_]*$ ]]; then
        die "$2: '$1' is not a valid program name (lowercase letters, digits and _, starting with a letter)"
    fi
    if [[ $reserved == *" $1 "* ]]; then
        die "$2: '$1' is reserved by the shell"
    fi
    if [[ -n ${where[$1]} ]]; then
        die "program '$1' is defined twice: ${where[$1]} and $2"
    fi
    if ! grep -qE '\bmain[[:space:]]*\(' "$3"; then
        die "$3: no main() found"
    fi
    where[$1]=$2
    mainsrc[$1]=$3
    names+=("$1")
}

shopt -s nullglob
for f in "$dir"/*.c; do
    n=$(basename "$f" .c)
    register "$n" "$f" "$f"
    files+=("$n")
done
for d in "$dir"/*/; do
    d=${d%/}
    n=$(basename "$d")
    [ -f "$d/main.c" ] || die "$d/: a program folder needs a main.c"
    register "$n" "$d/" "$d/main.c"
    dirs+=("$n")
done

case $mode in
vars)
    echo "BFILES := ${files[*]}"
    echo "BDIRS := ${dirs[*]}"
    ;;
table)
    echo "/* generated by tools/builtins.sh, do not edit */"
    echo '#include "shell.h"'
    echo
    sorted=$(printf '%s\n' "${names[@]}" | sort)
    for n in $sorted; do echo "extern int ${n}_main(int, char **);"; done
    echo
    echo "const struct command builtins[] = {"
    for n in $sorted; do
        help=$(sed -n 's|^// *help: *||p' "${mainsrc[$n]}" | head -n1 | sed 's/\\/\\\\/g; s/"/\\"/g')
        echo "    { \"$n\", ${n}_main, \"$help\" },"
    done
    echo "    { 0, 0, 0 }"
    echo "};"
    ;;
*)
    die "usage: builtins.sh vars|table [dir]"
    ;;
esac